import type { OralQuestion, OralTopic, OralTrack } from "./types";

const P: OralTrack[] = ["private", "commercial"];
const A: OralTrack[] = ["private", "commercial", "instrument"];
const I: OralTrack[] = ["instrument"];
const C: OralTrack[] = ["commercial"];

type ConceptSpec = [label: string, weight: number, keywords: string[]];
type FollowSpec = [question: string, targets: number[]];

function o(
  id: string,
  topic: OralTopic,
  tracks: OralTrack[],
  difficulty: 1 | 2 | 3,
  question: string,
  hint: string,
  concepts: ConceptSpec[],
  modelAnswer: string,
  followUps: FollowSpec[],
  extra?: { scenario?: string; ref?: string },
): OralQuestion {
  const out: OralQuestion = {
    id,
    topic,
    tracks,
    difficulty,
    question,
    hint,
    concepts: concepts.map(([label, weight, keywords], i) => ({
      id: `${id}.c${i}`,
      label,
      weight,
      keywords,
    })),
    modelAnswer,
    followUps: followUps.map(([q, t]) => ({ question: q, targets: t.map((i) => `${id}.c${i}`) })),
  };
  if (extra?.scenario) out.scenario = extra.scenario;
  if (extra?.ref) out.reference = extra.ref;
  return out;
}

